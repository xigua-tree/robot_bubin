/**
  * @brief This function handles USART3 global interrupt.
  */
void USART3_IRQHandler(void)
{
  /* USER CODE BEGIN USART3_IRQn 0 */
  /* 直接读取 RXNE 标志，绕过 HAL（保证低延迟） */
  if (USART3->SR & USART_SR_RXNE) {
      uint8_t c = (uint8_t)(USART3->DR & 0xFF);
      RingBuf_Put(&s_uart_rx_rb, c);
      return;  /* 已处理，不进入 HAL_UART_IRQHandler */
  }
  /* 清除溢出标志 */
  if (USART3->SR & USART_SR_ORE) {
      (void)USART3->DR;
      (void)USART3->SR;
  }
  /* USER CODE END USART3_IRQn 0 */
  HAL_UART_IRQHandler(&huart3);
  /* USER CODE BEGIN USART3_IRQn 1 */

  /* USER CODE END USART3_IRQn 1 */
}

/**
  * @brief This function handles TIM8 update interrupt and TIM13 global interrupt.***10KHZ
  */
void TIM8_UP_TIM13_IRQHandler(void)
{
  /* USER CODE BEGIN TIM8_UP_TIM13_IRQn 0 */
  if (__HAL_TIM_GET_FLAG(&htim8, TIM_FLAG_UPDATE) != RESET) {
      __HAL_TIM_CLEAR_FLAG(&htim8, TIM_FLAG_UPDATE);  
      s_tim8_divider++;
      s_tim8_encoder_counter++;
      oled_Counter++;

      if(oled_Counter >= 1000){
        oled_task_flag = 1;
        oled_Counter = 0;
      }
      if (s_tim8_divider >= 500) {
          tim8_counter++;
          s_tim8_divider = 0;
          g_speed_ctrl_flag = 1;
          /* ---- 速度控制（由 TIM8 ISR 标志驱动） ---- */
        if (g_speed_ctrl_flag) {
            // Motor_SetDuty(&g_motors[0],8000);
            // SpeedCtrl_UpdateEncoders();
            SpeedCtrl_1kHz_Tick();
            g_speed_ctrl_flag = 0;
        }
      }
      return;  /* 已处理，不进入 HAL_TIM_IRQHandler */
  }
  /* USER CODE END TIM8_UP_TIM13_IRQn 0 */
  HAL_TIM_IRQHandler(&htim8);
  /* USER CODE BEGIN TIM8_UP_TIM13_IRQn 1 */

  /* USER CODE END TIM8_UP_TIM13_IRQn 1 */
}

